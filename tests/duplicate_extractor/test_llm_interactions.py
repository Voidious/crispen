def test_generate_no_arg_call_indented():
    seq = _make_seq_info(7, 9, "    x = 1\n    y = 2\n")
    func = _FunctionInfo(
        name="setup",
        source="def setup(): pass\n",
        scope="<module>",
        body_source="    pass\n",
        body_stmt_count=1,
        params=[],
    )
    result = _generate_no_arg_call(seq, func)
    assert result == "    setup()\n"


